    @KafkaListener(
            topics           = "client-onboarded",
            groupId          = "notification-service-group",
            containerFactory = "kafkaListenerContainerFactory"
    )
    public void onClientOnboarded(ClientOnboardedEvent event) {
        log.info("Consuming CLIENT_ONBOARDED for clientId={}", event.getClientId());
        NotificationTemplate template = requireTemplate(CLIENT_ONBOARDED);

        Map<String, Object> vars = new HashMap<>();
        vars.put("firstName",   event.getFirstName());
        vars.put("lastName",    event.getLastName());
        vars.put("email",       event.getEmail());
        vars.put("clientId",    event.getClientId());
        vars.put("accountId",   event.getAccountId());

        emailService.send(event.getEmail(), template.getSubject(),
                template.getBodyTemplateName(), CLIENT_ONBOARDED, vars);
    }

