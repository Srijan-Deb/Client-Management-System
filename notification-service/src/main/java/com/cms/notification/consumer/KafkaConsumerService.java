    private NotificationTemplate requireTemplate(String eventType) {
        return templateRepository.findByEventType(eventType)
                .orElseThrow(() -> new IllegalStateException(
                        "No notification template found for event type: " + eventType +
                        ". Check V5 migration seed data."));
    }

    private String extractString(Map<String, Object> event, String key) {
        Object value = event.get(key);
        if (value == null) {
            log.warn("Event payload missing field '{}' Ã¢â‚¬â€ event: {}", key, event);
            return "unknown@example.com";
        }
        return value.toString();
    }
